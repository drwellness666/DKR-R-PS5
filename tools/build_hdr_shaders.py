"""Compile authored HDR GLSL and verify the actual embedded SPIR-V and provenance."""
import argparse,hashlib,json,pathlib,re,struct,subprocess,tempfile
r=pathlib.Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
compiler=subprocess.check_output(['glslangValidator','--version'],text=True)
text='// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by tools/build_hdr_shaders.py from the adjacent authored GLSL.\n#pragma once\n#include <cstdint>\n'
record={'compiler':compiler,'sources':{},'spirv':{}}
header=r/'src/ps5_hdr_shaders.h';meta=r/'src/ps5_hdr_shaders.json'
with tempfile.TemporaryDirectory(prefix='dkrr-hdr-shaders-') as d:
 for stage in ('vert','frag'):
  source=r/'src'/('ps5_hdr.'+stage);output=pathlib.Path(d)/(stage+'.spv')
  subprocess.run(['glslangValidator','-V','--target-env','vulkan1.1',str(source),'-o',str(output)],check=True)
  subprocess.run(['spirv-val','--target-env','vulkan1.1',str(output)],check=True)
  b=output.read_bytes();assert b'/home/' not in b and b'/Users/' not in b
  record['sources'][source.name]=hashlib.sha256(source.read_bytes()).hexdigest();record['spirv'][stage]=hashlib.sha256(b).hexdigest()
  words=struct.unpack('<'+'I'*(len(b)//4),b)
  text+='inline constexpr std::uint32_t dkrr_hdr_'+stage+'[] = {\n'
  text+='\n'.join('    '+','.join(f'0x{x:08x}' for x in words[i:i+8])+',' for i in range(0,len(words),8))+'\n};\n'
 if a.check:
  previous=json.loads(meta.read_text())
  if previous['sources']!=record['sources']:raise SystemExit('Authored HDR source changed without regenerating embedded shader')
  for stage in ('vert','frag'):
   match=re.search(r'dkrr_hdr_'+stage+r'\[\] = \{([^}]+)\}',header.read_text());assert match
   words=[int(x,16) for x in re.findall(r'0x[0-9a-f]{8}',match[1])];b=struct.pack('<'+'I'*len(words),*words)
   if hashlib.sha256(b).hexdigest()!=previous['spirv'][stage]:raise SystemExit('Embedded HDR shader differs from the recorded build')
   path=pathlib.Path(d)/('embedded-'+stage+'.spv');path.write_bytes(b);subprocess.run(['spirv-val','--target-env','vulkan1.1',str(path)],check=True)
  if previous['compiler']==compiler:
   if header.read_text()!=text:raise SystemExit('Same-compiler HDR shader rebuild differs')
   print('PASS exact same-compiler HDR SPIR-V rebuild')
  else:print('PASS HDR source hashes, recorded embedded SPIR-V validation and current-compiler build; compiler versions differ')
 else:
  header.write_text(text);meta.write_text(json.dumps(record,indent=2)+'\n')
print('PASS authored and embedded HDR shaders; no runtime shader compiler or game assets')
